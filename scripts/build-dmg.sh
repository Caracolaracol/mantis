#!/bin/bash
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
APP="${MANTIS_APP:-$ROOT/build/Mantis.app}"
PLIST="$APP/Contents/Info.plist"
[[ -f "$PLIST" ]] || { printf 'Falta Mantis.app. Primero compila la app con scripts/build-app.sh.\n' >&2; exit 1; }
VERSION="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$PLIST")"
OUTPUT="${1:-$ROOT/build/Mantis-$VERSION.dmg}"
[[ "$OUTPUT" = /* ]] || OUTPUT="$PWD/$OUTPUT"
[[ ! -e "$OUTPUT" && ! -e "$OUTPUT.sha256" ]] || { printf 'El destino ya existe; no se sobrescribirá: %s\n' "$OUTPUT" >&2; exit 1; }

# Package the existing signed bundle, without rebuilding/re-signing it or touching TCC.
codesign --verify --deep --strict "$APP"
TEMP_ROOT="${MANTIS_PACKAGE_TEMP:-${TMPDIR:-/private/tmp}/opencode}"
mkdir -p "$TEMP_ROOT" "$(dirname "$OUTPUT")"
WORK="$(mktemp -d "$TEMP_ROOT/mantis-dmg.XXXXXX")"
cleanup() {
  # This directory was generated by this script; never remove a user-supplied path.
  case "$WORK" in "$TEMP_ROOT"/mantis-dmg.*) rm -rf -- "$WORK" ;; esac
}
trap cleanup EXIT
STAGE="$WORK/contents"
mkdir "$STAGE"
ditto "$APP" "$STAGE/Mantis.app"
ln -s /Applications "$STAGE/Applications"
touch "$STAGE/.metadata_never_index"
codesign --verify --deep --strict "$STAGE/Mantis.app"

hdiutil create -srcfolder "$STAGE" -volname 'Mantis — Drag to Applications' \
  -fs HFS+ -format UDZO "$WORK/Mantis.dmg"
hdiutil verify "$WORK/Mantis.dmg"
mv -n "$WORK/Mantis.dmg" "$OUTPUT"
[[ ! -e "$WORK/Mantis.dmg" ]] || { printf 'El destino apareció durante el empaquetado; no se sobrescribió.\n' >&2; exit 1; }
CHECKSUM="$(shasum -a 256 "$OUTPUT" | awk '{print $1}')"
printf '%s  %s\n' "$CHECKSUM" "$(basename "$OUTPUT")" > "$OUTPUT.sha256"
printf '\nDMG creado (no instalado ni abierto):\n%s\nSHA-256: %s\n' "$OUTPUT" "$CHECKSUM"
